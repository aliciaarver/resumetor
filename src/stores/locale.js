function detectDefaultLocale() {
    if (typeof navigator === "undefined") {
        return "en";
    }
    return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}
function resolveMessage(locale, key) {
    let current = messages[locale];
    for (const segment of key.split(".")) {
        if (typeof current === "string") {
            return key;
        }
        const next = current[segment];
        if (!next) {
            return key;
        }
        current = next;
    }
    return typeof current === "string" ? current : key;
}
function interpolate(template, params) {
    if (!params) {
        return template;
    }
    return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));
}
export const useLocaleStore = defineStore("locale", () => {
    const locale = useLocalStorage("resumetor:locale", detectDefaultLocale());
    function t(key, params) {
        return interpolate(resolveMessage(locale.value, key), params);
    }
    function setLocale(nextLocale) {
        locale.value = nextLocale;
    }
    function proficiencyLabel(value) {
        return t(`proficiency.${value}`);
    }
    const proficiencyOptions = computed(() => PROFICIENCY_ORDER.map((value) => ({
        value,
        label: proficiencyLabel(value),
    })));
    function socialLinkLabel(value) {
        const normalized = normalizeSocialLinkLabel(value);
        const keyByType = {
            Email: "form.linkTypeEmail",
            LinkedIn: "form.linkTypeLinkedIn",
            Telegram: "form.linkTypeTelegram",
            GitHub: "form.linkTypeGitHub",
            Link: "form.linkTypeOther",
        };
        return t(keyByType[normalized]);
    }
    const socialLinkOptions = computed(() => SOCIAL_LINK_TYPES.map((value) => ({
        value,
        label: socialLinkLabel(value),
    })));
    watch(locale, (value) => {
        if (typeof document !== "undefined") {
            document.documentElement.lang = value;
        }
    }, { immediate: true });
    return {
        locale,
        locales: AVAILABLE_LOCALES,
        proficiencyOptions,
        socialLinkOptions,
        t,
        setLocale,
        proficiencyLabel,
        socialLinkLabel,
    };
});
